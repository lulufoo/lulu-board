import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const __dirname = require('path').dirname(fileURLToPath(import.meta.url));
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const Style = require('../../packages/drawer-app/src/core/style-line.js').default;

const root = path.join(__dirname, '../..');
const src = fs.readFileSync(path.join(root, 'packages/drawer-app/templates/sketch.skt'), 'utf8');
const html = fs.readFileSync(path.join(root, 'packages/drawer-app/index.html'), 'utf8');
const mount = fs.readFileSync(path.join(root, 'packages/drawer-app/src/kinds/sketch.js'), 'utf8');

assert.strictEqual(Style.bodyKind(src), 'sketch');
assert.doesNotMatch(src, /(?:style|content)\s+\{/);
const fragment = Style.decodeSketchContent(src);
assert.match(src, /sketch "A HTML board"/);
assert.match(fragment, /A <span class="q">HTML<\/span> board/);
assert.match(fragment, /Copy this link\. Use the \/sketch skill in an AI agent to edit this\./);
assert.match(fragment, /Content is written by AI/);
assert.match(fragment, />Sketch</);
assert.doesNotMatch(fragment, /A quiet board/);
assert.doesNotMatch(fragment, /Warm sand inside the board\./);
assert.doesNotMatch(fragment, /#d0d7de/);
assert.doesNotMatch(fragment, /<script/i);
assert.match(html, /style-src 'self' 'unsafe-inline'/);
assert.match(html, /script-src 'self'/);
assert.doesNotMatch(html, /script-src 'self' 'unsafe-inline'/);
assert.match(mount, /"iframe, object, embed, link"/, 'Nested documents and external links are still removed');
assert.doesNotMatch(mount, /querySelectorAll\("script/, 'Scripts run in the runner and are not filtered');
assert.doesNotMatch(mount, /\^on\/i/, 'Event handler attributes run in the runner and are not filtered');
assert.match(mount, /createElement\("iframe"\)/, 'Sketch mounts in its own document');
assert.match(mount, /setAttribute\("sandbox", "allow-scripts"\)/, 'Sketch iframe may run scripts');
assert.doesNotMatch(mount, /setAttribute\("sandbox",[^)]*allow-same-origin/, 'Sketch iframe never gets an origin back');
assert.doesNotMatch(mount, /allow-(top-navigation|popups|forms|modals|downloads|pointer-lock)/, 'Sketch iframe gets no permission beyond scripts');
assert.match(mount, /SKETCH_RUNNER_URL = "https:\/\/sandbox\.luluboard\.app\/"/, 'Runner lives on its own origin');
assert.match(mount, /frame\.src = SKETCH_RUNNER_URL/, 'Frame loads the runner');
assert.doesNotMatch(mount, /srcdoc/, 'Fragment no longer shares an origin through srcdoc');
assert.doesNotMatch(mount, /contentDocument/, 'Board never reads into the frame');
assert.match(mount, /event\.source !== frame\.contentWindow \|\| event\.origin !== "null"/, 'Messages must come from this frame, which has an opaque origin');
assert.match(mount, /parseSize\(event\.data\)/, 'Size comes through the protocol parser');
assert.match(mount, /renderMessage\(html\)/, 'Fragment travels as a protocol message');
assert.match(mount, /export function captureSketch\(frame, scale\)/, 'Export asks the runner through one function');
assert.match(mount, /captureMessage\(id, scale\)/, 'Capture travels as a protocol message');
assert.match(mount, /parseCaptured\(event\.data\)/, 'A bitmap comes back through the protocol parser');
assert.match(mount, /failCaptures\("Sketch was replaced/, 'A replaced sketch fails its waiting captures');
assert.match(mount, /CAPTURE_TIMEOUT_MS/, 'A silent runner cannot hold an export forever');
assert.match(mount, /pointer-events:none/, 'Canvas keeps pan and zoom over the sketch');
assert.doesNotMatch(mount, /attachShadow/, 'Sketch does not share the Board document');
assert.doesNotMatch(mount, /previewEl\.appendChild\(sketchFragmentRoot/, 'Fragment does not mount in the Board document');
assert.match(html, /frame-src https:\/\/sandbox\.luluboard\.app;/, 'Board page may frame the runner and nothing else');

console.log('ok sketch template');
