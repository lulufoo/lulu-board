import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const __dirname = require('path').dirname(fileURLToPath(import.meta.url));
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const Style = require('../../packages/drawer-app/src/core/style-line.js').default;

const root = path.join(__dirname, '../..');
const src = fs.readFileSync(path.join(root, 'packages/drawer-app/templates/sketch.skt'), 'utf8');
const html = fs.readFileSync(path.join(root, 'packages/drawer-app/index.html'), 'utf8');
const mount = fs.readFileSync(path.join(root, 'packages/drawer-app/src/kinds/sketch.js'), 'utf8');

assert.strictEqual(Style.bodyKind(src), 'sketch');
assert.doesNotMatch(src, /(?:style|content)\s+\{/);
const fragment = Style.decodeSketchContent(src);
assert.match(src, /sketch "A HTML board"/);
assert.match(fragment, /A <span class="q">HTML<\/span> board/);
assert.match(fragment, /Copy this link\. Use the \/sketch skill in an AI agent to edit this\./);
assert.match(fragment, /Content is written by AI/);
assert.match(fragment, />Sketch</);
assert.doesNotMatch(fragment, /A quiet board/);
assert.doesNotMatch(fragment, /Warm sand inside the board\./);
assert.doesNotMatch(fragment, /#d0d7de/);
assert.doesNotMatch(fragment, /<script/i);
assert.match(html, /style-src 'self' 'unsafe-inline'/);
assert.match(html, /script-src 'self'/);
assert.doesNotMatch(html, /script-src 'self' 'unsafe-inline'/);
assert.match(mount, /"iframe, object, embed, link"/, 'Nested documents and external links are still removed');
assert.doesNotMatch(mount, /querySelectorAll\("script/, 'Scripts are refused by the sandbox, not filtered');
assert.doesNotMatch(mount, /\^on\/i/, 'Event handler attributes are refused by the sandbox, not filtered');
assert.match(mount, /createElement\("iframe"\)/, 'Sketch mounts in its own document');
assert.match(mount, /setAttribute\("sandbox", "allow-same-origin"\)/, 'Sketch iframe is sandboxed');
assert.doesNotMatch(mount, /allow-scripts/, 'Sketch iframe never allows scripts');
assert.match(mount, /frame\.srcdoc = /, 'Fragment is delivered through srcdoc');
assert.match(mount, /pointer-events:none/, 'Canvas keeps pan and zoom over the sketch');
assert.doesNotMatch(mount, /attachShadow/, 'Sketch does not share the Board document');
assert.doesNotMatch(mount, /previewEl\.appendChild\(sketchFragmentRoot/, 'Fragment does not mount in the Board document');

console.log('ok sketch template');
